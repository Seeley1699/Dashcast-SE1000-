    printf '%s\n' "$BUF" > $OUT/veh.tmp 2>/dev/null
    mv $OUT/veh.tmp $OUT/veh.txt 2>/dev/null
    chown $UID_GID:$UID_GID $OUT/veh.txt 2>/dev/null
    chcon $CTX $OUT/veh.txt 2>/dev/null
    chmod 660 $OUT/veh.txt 2>/dev/null
  fi
  sleep 0.4
