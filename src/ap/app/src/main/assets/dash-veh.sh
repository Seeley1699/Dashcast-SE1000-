  BUF=$(dumpsys car_service get-property-value 2>/dev/null \
    | grep -Ei '0x11600207|0x11400408|0x11400e00|0x11400e01|0x11400e02|0x11400e03|0x11400401|0x21408064|0x11600308|0x2160719b|0x17600309|0x21707479|0x2170747a|0x217075a8|0x11600104|0x11600106|0x21607337|0x2160733c|0x21607300|0x216072ff|0x11600307|0x11600703|0x2140710c')
